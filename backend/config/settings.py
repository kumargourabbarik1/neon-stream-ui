# TOTP secrets are encrypted before reaching the database. Production must set
# a dedicated Fernet key; the DEBUG-only value is deterministic so local data
# remains readable after a development-server restart.
TOTP_ENCRYPTION_KEY = os.getenv("TOTP_ENCRYPTION_KEY")
if not TOTP_ENCRYPTION_KEY:
    if not DEBUG:
        raise RuntimeError("TOTP_ENCRYPTION_KEY must be configured when DEBUG is false.")
    TOTP_ENCRYPTION_KEY = base64.urlsafe_b64encode(hashlib.sha256(SECRET_KEY.encode()).digest()).decode()

